#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>
#include "clings.h"
#include "buf.h"
#include "dev.h"
#include "info.h"

static void esc(const char *s, size_t n, const char *want) {
    struct buf b;
    buf_init(&b);
    embedded_escape_line(s, n, &b);
    CHECK_EQ_STR(b.data ? b.data : "", want);
    buf_free(&b);
}

static void test_escape(void) {
    esc("a\"b\\c?d\t", 8, "a\\\"b\\\\c\\?d\\t");
    esc("\xc3\xa9", 2, "\\303\\251");
    esc("", 0, "");
    esc("x\ny", 3, "x\\012y");
}

static void test_generate(void) {
    char cwd[1024];
    CHECK(getcwd(cwd, sizeof cwd) != NULL);
    char tmpl[] = "/tmp/clings-dev-XXXXXX";
    CHECK(mkdtemp(tmpl) != NULL);
    CHECK(chdir(tmpl) == 0);
    CHECK(mkdir("exercises", 0755) == 0);
    CHECK(mkdir("exercises/t", 0755) == 0);
    CHECK(file_write("exercises/t/x.c", "line one\nline two\n", 18));

    struct info_file f = {0};
    char err[256] = "";
    CHECK(info_parse("format_version = 1\n[[exercises]]\nname = \"x\"\ndir = \"t\"\nhint = \"h\"\n",
                     &f, err, sizeof err));
    struct buf out;
    buf_init(&out);
    dev_generate_embedded(&f, &out);
    CHECK(strstr(out.data, "/* Generated by clings dev update. Do not edit. */\n") == out.data);
    CHECK(strstr(out.data, "{ \"exercises/t/x.c\",\n    \"line one\\n\"\n    \"line two\\n\"\n},") != NULL);
    CHECK(strstr(out.data, "const char *embedded_lookup(const char *path)") != NULL);

    struct buf again;
    buf_init(&again);
    dev_generate_embedded(&f, &again);
    CHECK(out.len == again.len && memcmp(out.data, again.data, out.len) == 0);
    buf_free(&again);
    buf_free(&out);
    info_free(&f);

    CHECK(chdir(cwd) == 0);
    char cmd[1100];
    snprintf(cmd, sizeof cmd, "rm -rf %s", tmpl);
    CHECK(system(cmd) == 0);
}

int main(void) {
    test_escape();
    test_generate();
    return clings_summary();
}

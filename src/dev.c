#include "dev.h"

#include <stdio.h>
#include <string.h>

void embedded_escape_line(const char *line, size_t n, struct buf *out) {
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)line[i];
        if (c == '\\') buf_appends(out, "\\\\");
        else if (c == '"') buf_appends(out, "\\\"");
        else if (c == '?') buf_appends(out, "\\?");
        else if (c == '\t') buf_appends(out, "\\t");
        else if (c < 0x20 || c > 0x7e) buf_printf(out, "\\%03o", c);
        else buf_append(out, line + i, 1);
    }
}

/* False (naming the file in *bad) when an exercise cannot be read. */
static bool generate(const struct info_file *info, struct buf *out, const char **bad) {
    buf_appends(out,
                "/* Generated by clings dev update. Do not edit. */\n"
                "#include \"embedded.h\"\n"
                "\n"
                "static const struct embedded_file FILES[] = {\n");
    for (size_t i = 0; i < info->n; i++) {
        const char *path = info->exercises[i].path;
        struct buf src;
        buf_init(&src);
        if (!file_read(path, &src)) {
            buf_free(&src);
            *bad = path;
            return false;
        }
        buf_printf(out, "{ \"%s\",\n", path);
        size_t pos = 0;
        if (src.len == 0) buf_appends(out, "    \"\"\n");
        while (pos < src.len) {
            const char *nl = memchr(src.data + pos, '\n', src.len - pos);
            size_t end = nl ? (size_t)(nl - src.data) : src.len;
            buf_appends(out, "    \"");
            embedded_escape_line(src.data + pos, end - pos, out);
            buf_appends(out, nl ? "\\n\"\n" : "\"\n");
            pos = nl ? end + 1 : end;
        }
        buf_appends(out, "},\n");
        buf_free(&src);
    }
    buf_appends(out,
                "};\n"
                "\n"
                "const char *embedded_lookup(const char *path) {\n"
                "    for (size_t i = 0; i < sizeof FILES / sizeof FILES[0]; i++)\n"
                "        if (strcmp(FILES[i].path, path) == 0) return FILES[i].contents;\n"
                "    return NULL;\n"
                "}\n");
    return true;
}

void dev_generate_embedded(const struct info_file *info, struct buf *out) {
    const char *bad = NULL;
    if (!generate(info, out, &bad)) die("cannot read %s", bad);
}

static int update_embedded(const struct info_file *info) {
    struct buf out;
    buf_init(&out);
    const char *bad = NULL;
    if (!generate(info, &out, &bad)) {
        buf_free(&out);
        fprintf(stderr, "clings: cannot read %s\n", bad);
        return 2;
    }
    bool ok = file_write("src/embedded.c", out.data, out.len);
    buf_free(&out);
    if (!ok) {
        fputs("clings: cannot write src/embedded.c\n", stderr);
        return 2;
    }
    puts("Updated src/embedded.c");
    return 0;
}

int dev_update(const struct info_file *info) {
    return update_embedded(info);
}
